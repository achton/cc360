package tui

import (
	"os"
	"strings"

	"github.com/achton/cc360/internal/config"
	"github.com/achton/cc360/internal/db"
)

// VisibleSessions drops sessions that cannot or should not be resumed from the
// table: non-interactive runs, agent-team teammates, sidechains when hidden,
// and sessions whose project dir is gone.
func VisibleSessions(all []db.Session, cfg config.Config) []db.Session {
	out := make([]db.Session, 0, len(all))
	for _, s := range all {
		if cfg.HideSidechains && s.IsSidechain {
			continue
		}
		// Legacy index entries can still open with the local-command caveat.
		text := s.ExistingSummary + s.FirstPrompt
		if strings.Contains(text, "Caveat: The messages below were generated by the user while running") {
			continue
		}
		if strings.HasPrefix(s.FirstPrompt, "<teammate-message") {
			continue
		}
		if s.ProjectPath != "" {
			if _, err := os.Stat(s.ProjectPath); err != nil {
				continue
			}
		}
		out = append(out, s)
	}
	return out
}
